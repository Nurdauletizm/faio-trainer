def gen(rng):
    p = rng.choice([0.5, 1, 2, 3, 5, 10])
    s = rng.choice([90, 95, 97, 98, 99])
    t = rng.choice([90, 95, 96, 98, 99])
    return f"{p} {s} {t}\n", {}


def _answer(p, s, t):
    p, s, t = p / 100, s / 100, t / 100
    return p * s / (p * s + (1 - p) * (1 - t))


def solve(inp):
    p, s, t = [float(x) for x in inp.split()]
    return f"{_answer(p, s, t):.4f}\n"


def check(inp, out, payload):
    p, s, t = [float(x) for x in inp.split()]
    return cmp_numbers(out, [_answer(p, s, t)], rel=1e-4, abs_=1e-4, names=["вероятность"])
