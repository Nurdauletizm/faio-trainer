def gen(rng):
    x = rng.randint(1, 5000)
    g = rng.randint(1, x)
    return f"{x} {g}\n", {}


def solve(inp):
    x, g = [int(v) for v in inp.split()]
    return f"{(x + 1) / (g + 1):.6f}\n"


def check(inp, out, payload):
    x, g = [int(v) for v in inp.split()]
    return cmp_numbers(out, [(x + 1) / (g + 1)], rel=1e-4, abs_=1e-4, names=["матожидание"])
